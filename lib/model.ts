// Token Radar, model radar-2.
//
// One sealed snapshot in, one ranked board out. The board ranks protocols that
// record no token, by an implied value that follows only from the snapshot's
// own figures: TVL, seven-day TVL change, and age since first listing. No
// protocol name is ever special-cased; the same function scores every row.
//
//   base      = tvl_usd x 0.25
//   growth    = clamp(change_7d, -60, +120) per cent; unreported growth = 0
//   growthMul = 1 + (growth / 100) x 0.5
//   maturity  = 0.6 + min(age_days, 1095) / 1095 x 0.4
//   implied   = max(1, round(base x growthMul x maturity))
//
// Why these constants. 0.25 is a conservative launch multiple: a new token
// rarely sustains a fully-diluted value above a quarter of the TVL it already
// secures, and the same multiple for every row keeps the ranking a ranking of
// the snapshot, not of an opinion. Growth is clamped so one hot week cannot
// more than double a row and one bad week cannot zero it, and it is weighted
// 0.5 so size still dominates momentum. Maturity rewards survival: a protocol
// that has run for three years with no token on record has had three years to
// build the user base a launch would price, while a protocol listed last month
// has not; the floor 0.6 keeps young protocols in the race. An unlisted age
// uses 365 days, the middle of the maturity range, so a missing date neither
// rewards nor punishes the row. Age and growth are reported separately from
// the value, so a reader can see which input moved a row.
//
// Two things are shown but never enter the value, deliberately. Category and
// chain decide the farm plan, not the price: a lending protocol and a DEX of
// the same size and age earn the same implied value, because the snapshot
// carries no yield, fee or user figure that would justify pricing one above
// the other. And a confidence label (high / medium / low) records whether the
// snapshot actually reported the row's age and growth: a row whose age is
// unknown and whose growth is unreported is still ranked, but the reader is
// told its inputs were thin. A tier (S / A / B / C) is the rank percentile,
// so the board reads at a glance without changing any number.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.25,
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
};

export const MODEL_VERSION = 'radar-2';

/** Pre-token protocols below the watchlist floor carried by the early radar, by TVL. */
export const EARLY_ROWS = 160;

/** Live-token protocols carried in the separate Live view, by market cap. */
export const LIVE_ROWS = 24;

